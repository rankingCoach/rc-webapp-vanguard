import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { describe, expect, it } from 'vitest';

/**
 * Plan §26: types/_vendor/mui.d.ts is GENERATED. Regenerating it from its manifest (the MUI type names the published
 * declarations import) must reproduce the shipped file byte for byte, so it is deterministic and never hand-edited.
 */
const root = resolve(__dirname, '..');

describe.each([['default', 'dist/types'], ['WordPress', 'dist-wordpress/types']])('vendored MUI types (%s)', (_n, rel) => {
  const vendored = join(root, rel, '_vendor', 'mui.d.ts');
  const manifestPath = join(root, rel, '_vendor', 'mui.manifest.json');
  it.skipIf(!existsSync(manifestPath))('regenerates byte for byte from its manifest', () => {
    const manifest = JSON.parse(readFileSync(manifestPath, 'utf8')) as Record<string, string[]>;
    const dir = mkdtempSync(join(tmpdir(), 'vg-vendor-spec-'));
    try {
      mkdirSync(join(dir, 'types'));
      writeFileSync(
        join(dir, 'types', 'probe.d.ts'),
        `${Object.entries(manifest)
          .map(([spec, names]) => `import type { ${names.join(', ')} } from '${spec}';`)
          .join('\n')}\nexport {};\n`,
      );
      execFileSync('node', [join(root, 'scripts', 'vendor-mui-types.mjs'), join(dir, 'types')], { cwd: root });
      expect(readFileSync(join(dir, 'types', '_vendor', 'mui.d.ts'), 'utf8')).toBe(readFileSync(vendored, 'utf8'));
    } finally {
      rmSync(dir, { recursive: true, force: true });
    }
  });

  it.skipIf(!existsSync(vendored))('starts with the generated marker and the licence notices', () => {
    const head = readFileSync(vendored, 'utf8').slice(0, 400);
    expect(head).toContain('GENERATED by scripts/vendor-mui-types.mjs');
    expect(readFileSync(vendored, 'utf8')).toMatch(/@mui\/material@[\d.]+ \(MIT\)/);
  });
});
