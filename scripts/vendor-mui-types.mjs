#!/usr/bin/env node
/**
 * Plan §26: published declarations must not import @mui/* (rc-webapp only has MUI transitively through Vanguard).
 * This post-build step rolls exactly the MUI types the emitted .d.ts files import (with @mui/*, @emotion/*,
 * react-transition-group and @popperjs/core inlined) into <typesDir>/_vendor/mui.d.ts with api-extractor, then
 * rewrites those imports to the vendored file. Public types stay identical; MUI is no longer needed to read them.
 *
 * Usage: node scripts/vendor-mui-types.mjs <typesDir> [<typesDir> ...]
 */
import { Extractor, ExtractorConfig } from '@microsoft/api-extractor';
import { existsSync, mkdirSync, mkdtempSync, readdirSync, readFileSync, rmSync, statSync, symlinkSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const MUI_IMPORT = /import\s+(type\s+)?\{([^}]*)\}\s+from\s+['"](@mui\/[^'"]+)['"];?/g;
const BUNDLED = [
  '@mui/material',
  '@mui/system',
  '@mui/types',
  '@mui/utils',
  '@mui/styled-engine',
  '@mui/private-theming',
  '@emotion/react',
  '@emotion/styled',
  '@emotion/serialize',
  '@emotion/utils',
  '@emotion/cache',
  '@emotion/sheet',
  '@popperjs/core',
  '@types/react-transition-group',
  'react-transition-group',
];

/** Licence header for the vendored file: every package whose types it inlines (deterministic order). */
const licenceHeader = () => {
  const blocks = [];
  for (const name of [...BUNDLED].sort()) {
    const dir = join(root, 'node_modules', ...name.split('/'));
    if (!existsSync(join(dir, 'package.json'))) continue;
    const pkg = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'));
    const file = readdirSync(dir).find((f) => /^(licen[cs]e|copying)([.-][\w.-]+)?$/i.test(f));
    const text = file ? readFileSync(join(dir, file), 'utf8').trim() : `(${pkg.license}; no licence file in the package)`;
    blocks.push(`${pkg.name}@${pkg.version} (${pkg.license})\n\n${text}`);
  }
  const body = blocks.join(`\n\n${'-'.repeat(76)}\n\n`).replace(/\*\//g, '* /');
  return `/*!\n * GENERATED by scripts/vendor-mui-types.mjs - do not edit.\n * Type declarations vendored from the packages below so Vanguard's published types do not need MUI installed.\n *\n${body
    .split('\n')
    .map((l) => ` * ${l}`.trimEnd())
    .join('\n')}\n */\n`;
};

const walk = (dir) =>
  readdirSync(dir).flatMap((name) => {
    const path = join(dir, name);
    if (statSync(path).isDirectory()) return name === '_vendor' ? [] : walk(path);
    return path.endsWith('.d.ts') ? [path] : [];
  });

const rollup = (work, entry, out) => {
  const config = ExtractorConfig.prepare({
    configObject: {
      projectFolder: work,
      mainEntryPointFilePath: join(work, entry),
      bundledPackages: BUNDLED,
      compiler: { tsconfigFilePath: join(work, 'tsconfig.json') },
      dtsRollup: { enabled: true, untrimmedFilePath: out },
      apiReport: { enabled: false },
      docModel: { enabled: false },
      tsdocMetadata: { enabled: false },
      messages: {
        extractorMessageReporting: { default: { logLevel: 'none' } },
        compilerMessageReporting: { default: { logLevel: 'error' } },
        tsdocMessageReporting: { default: { logLevel: 'none' } },
      },
    },
    configObjectFullPath: join(work, 'api-extractor.json'),
    packageJsonFullPath: join(work, 'package.json'),
  });
  const result = Extractor.invoke(config, { localBuild: true });
  if (!result.succeeded) throw new Error(`api-extractor failed on ${entry} (${result.errorCount} errors)`);
};

const vendor = (typesDir) => {
  const files = walk(typesDir);
  // specifier -> exported names (original names; local aliases stay in the importing file)
  const wanted = new Map();
  const users = [];
  for (const file of files) {
    const text = readFileSync(file, 'utf8');
    let used = false;
    for (const [, , names, specifier] of text.matchAll(MUI_IMPORT)) {
      used = true;
      const set = wanted.get(specifier) ?? new Set();
      for (const part of names.split(',')) {
        const name = part.trim().replace(/^type\s+/, '').split(/\s+as\s+/)[0];
        if (name) set.add(name);
      }
      wanted.set(specifier, set);
    }
    if (used) users.push(file);
  }
  if (users.length === 0) return { files: 0 };

  const names = new Map(); // exported name -> specifier (first wins; MUI names are unique across subpaths)
  for (const [specifier, set] of wanted) for (const name of set) if (!names.has(name)) names.set(name, specifier);

  const work = mkdtempSync(join(tmpdir(), 'vg-mui-types-'));
  try {
    writeFileSync(join(work, 'package.json'), JSON.stringify({ name: 'vanguard-mui-types', version: '0.0.0' }));
    symlinkSync(join(root, 'node_modules'), join(work, 'node_modules'), 'dir');
    const bySpecifier = new Map();
    for (const [name, specifier] of [...names].sort(([a], [b]) => a.localeCompare(b)))
      bySpecifier.set(specifier, [...(bySpecifier.get(specifier) ?? []), name]);
    writeFileSync(
      join(work, 'index.d.ts'),
      [...bySpecifier].map(([spec, list]) => `export type { ${list.join(', ')} } from '${spec}';`).join('\n') + '\n',
    );
    const nm = join(root, 'node_modules');
    writeFileSync(
      join(work, 'tsconfig.json'),
      JSON.stringify({
        compilerOptions: {
          strict: true,
          module: 'esnext',
          moduleResolution: 'bundler',
          target: 'es2020',
          jsx: 'react-jsx',
          skipLibCheck: true,
          types: [],
          typeRoots: [join(nm, '@types')],
        },
        include: ['index.d.ts', 'popper.d.ts'],
      }),
    );
    const out = join(typesDir, '_vendor', 'mui.d.ts');
    mkdirSync(dirname(out), { recursive: true });
    rollup(work, 'index.d.ts', out);
    let rolled = readFileSync(out, 'utf8');
    // @popperjs/core has no `types` field and re-exports './lib', which api-extractor keeps as an import: roll the
    // popper names it needs from popper's lib by file path (inlined as local source) and splice them in.
    const popperImport = /import\s*\{\s*([A-Za-z0-9_$]+)\s*\}\s*from\s*['"](?:@popperjs\/core|\.\/lib)['"];\n?/g;
    const popperNames = [...rolled.matchAll(popperImport)].map((m) => m[1]);
    if (popperNames.length) {
      const lib = join(root, 'node_modules', '@popperjs', 'core', 'lib', 'index');
      writeFileSync(join(work, 'popper.d.ts'), `export type { ${popperNames.join(', ')} } from '${lib}';\n`);
      const popperOut = join(work, 'popper-rolled.d.ts');
      rollup(work, 'popper.d.ts', popperOut);
      const popper = readFileSync(popperOut, 'utf8').replace(/^export \{\s*\};?\s*$/m, '');
      rolled = `${rolled.replace(popperImport, '')}\n// ---- @popperjs/core (vendored)\n${popper}`;
      writeFileSync(out, rolled);
    }
    rolled = licenceHeader() + rolled;
    writeFileSync(out, rolled);
    // What was vendored, so a spec can regenerate the file and byte-compare it (generated, never hand-edited).
    const manifest = Object.fromEntries([...bySpecifier].sort(([a], [b]) => a.localeCompare(b)).map(([k, v]) => [k, [...v].sort()]));
    writeFileSync(join(typesDir, '_vendor', 'mui.manifest.json'), `${JSON.stringify(manifest, null, 2)}\n`);
    const leftovers = [...rolled.matchAll(/from\s+['"]([^'"]+)['"]/g)].map((m) => m[1]).filter((s) => s !== 'react' && s !== 'csstype');
    if (leftovers.length) throw new Error(`vendored MUI types still import: ${[...new Set(leftovers)].join(', ')}`);
  } finally {
    rmSync(work, { recursive: true, force: true });
  }

  for (const file of users) {
    let rel = relative(dirname(file), join(typesDir, '_vendor', 'mui')).split(sep).join('/');
    if (!rel.startsWith('.')) rel = `./${rel}`;
    const text = readFileSync(file, 'utf8').replace(MUI_IMPORT, (_m, type, list) => `import ${type ?? ''}{${list}} from '${rel}';`);
    writeFileSync(file, text);
  }
  return { files: users.length, names: names.size };
};

const dirs = process.argv.slice(2);
if (dirs.length === 0) {
  console.error('usage: node scripts/vendor-mui-types.mjs <typesDir> [<typesDir> ...]');
  process.exit(2);
}
// The WordPress build also re-emits dist/types (its config merges the lib config's dts plugin), so it vendors both;
// a directory that does not exist is skipped, and a directory without @mui imports is left as it is.
for (const dir of dirs) {
  const typesDir = resolve(dir);
  if (!existsSync(typesDir)) {
    console.log(`vendor-mui-types: ${dir}: not found, skipped`);
    continue;
  }
  const { files, names } = vendor(typesDir);
  console.log(`vendor-mui-types: ${relative(root, typesDir)}: ${files} declaration files rewritten, ${names ?? 0} MUI types vendored`);
}
