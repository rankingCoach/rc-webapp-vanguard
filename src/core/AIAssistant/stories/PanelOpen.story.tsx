import React, { useState } from "react";
import { AIAssistantPanel } from "@vanguard/AIAssistant/AIAssistentPanel/AIAssistantPanel";
import { within, expect } from "storybook/test";
import { Story, createMockGenerateCallback, Container } from "./_AIAssistant.default";

/**
 * Renders the AIAssistantPanel directly in the `open` status, so the
 * keep / adjust / try again / remove buttons are visible without any interaction.
 */
export const PanelOpen: Story = {
  args: {
    anchorElem: null,
    generateCallback: createMockGenerateCallback(),
    value: "Some text generated by the AI assistant.",
    setValue: () => {},
  },
  render: (args) => {
    const [text, setText] = useState(args.value);

    return (
      <Container>
        {/* Positioned stand-in for the text field the panel is normally anchored to; the panel hangs below it */}
        <div style={{ position: "relative", padding: "12px", border: "1px solid var(--n200)", borderRadius: "8px" }}>
          {text}
          <AIAssistantPanel
            id="AIAssistantPanelOpen"
            value={text}
            setValue={setText}
            generateCallback={args.generateCallback}
            status="open"
            setStatus={() => {}}
          />
        </div>
      </Container>
    );
  },
  play: async ({ canvasElement }) => {
    const canvas = within(canvasElement);
    const panel = canvas.getByTestId("AIAssistantPanelOpen_Panel");
    await expect(panel).toBeInTheDocument();
    // Four muted icon buttons (keep, adjust, try again, remove); the close button is hidden on mobile
    await expect(within(panel).getAllByRole("button").length).toBeGreaterThanOrEqual(4);
  },
};
